#!/usr/bin/env python3
"""Generate crates/vkb-core/data/bigrams.rs: English word pairs for the D10 rule
"after an English word, a listed English word stays English".

Input: Tatoeba English sentences (CC BY 2.0 FR; credited in THIRD_PARTY_NOTICES.md), e.g.
  eng_sentences.tsv  (id <TAB> lang <TAB> text)  from downloads.tatoeba.org/exports/per_language/eng/
Usage: python3 scripts/gen_bigrams.py eng_sentences.tsv [--min 1]

A pair "prev cur" is kept when `cur` is a word of data/english.txt (a word Telex garbles).
The engine only consults the table when the Telex reading of `cur` is a real Vietnamese word
(room/box/max/mix/bus...), so the table stays small. Only hashes are stored (FNV-1a 32 of
"prev cur", same as lexicon::fnv_extend); no sentence text.
"""
import argparse, collections, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "..", "crates", "vkb-core", "data")


def fnv(text):
    h = 0x811C9DC5
    for b in text.encode():
        h = ((h ^ b) * 0x01000193) & 0xFFFFFFFF
    return h


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("sentences")
    ap.add_argument("--min", type=int, default=1, help="minimum occurrences of a pair")
    args = ap.parse_args()
    english = {l.strip()[:-1] for l in open(os.path.join(DATA, "english.txt")) if l.strip()}
    pairs = collections.Counter()
    for line in open(args.sentences, encoding="utf-8"):
        text = line.rstrip("\n").split("\t")[-1].lower()
        words = re.findall(r"[a-z]+", text)
        for prev, cur in zip(words, words[1:]):
            if cur in english:
                pairs[(prev, cur)] += 1
    hashes = sorted({fnv(f"{p} {c}") for (p, c), n in pairs.items() if n >= args.min})
    out = os.path.join(DATA, "bigrams.rs")
    with open(out, "w") as f:
        f.write("// @generated by scripts/gen_bigrams.py - do not edit.\n")
        f.write('// FNV-1a hashes of "previous current" English word pairs attested in English sentences. Sorted.\n')
        f.write(f"pub static ENGLISH_BIGRAMS: [u32; {len(hashes)}] = [\n")
        for i in range(0, len(hashes), 8):
            f.write("    " + ", ".join(str(h) for h in hashes[i:i + 8]) + ",\n")
        f.write("];\n")
    print(f"{len(hashes)} pairs -> {out}", file=sys.stderr)


if __name__ == "__main__":
    main()
