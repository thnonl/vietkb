pub const TRAY_ID: &str = "vietkb-tray";

const METHODS: [(&str, &str); 2] = [("telex", "Telex"), ("vni", "VNI")];

// Approved keycap mark (design/logo11/keycap): `V` = Vietnamese on, `E` = off.
// Windows takes one bitmap per tray icon, so the size is chosen from the
// monitor scale (16 px @100 %, 20 px @125/150 %, 32 px otherwise) instead of
// shipping a multi-size ICO.
#[cfg(not(target_os = "macos"))]
const ON_16: &[u8] = include_bytes!("../icons/tray-on-16.png");
#[cfg(not(target_os = "macos"))]
const ON_20: &[u8] = include_bytes!("../icons/tray-on-20.png");
#[cfg(not(target_os = "macos"))]
const ON_32: &[u8] = include_bytes!("../icons/tray-on-32.png");
#[cfg(not(target_os = "macos"))]
const OFF_16: &[u8] = include_bytes!("../icons/tray-off-16.png");
#[cfg(not(target_os = "macos"))]
const OFF_20: &[u8] = include_bytes!("../icons/tray-off-20.png");
#[cfg(not(target_os = "macos"))]
const OFF_32: &[u8] = include_bytes!("../icons/tray-off-32.png");

// macOS: monochrome template images (black + alpha, generated by
// `scripts/gen-mac-tray-icons.py`) so the menu bar tints them for light, dark
// and highlighted states. `V` = filled key with the letter cut out (on),
// `E` = outlined key with a solid letter (off). The menu bar is drawn at 18 pt,
// so the @2x (32 px) bitmaps are the ones used; the 16 px @1x set ships for
// completeness.
#[cfg(target_os = "macos")]
const MAC_ON: &[u8] = include_bytes!("../icons/tray-mac-on-32.png");
#[cfg(target_os = "macos")]
const MAC_OFF: &[u8] = include_bytes!("../icons/tray-mac-off-32.png");

/// Physical tray size for the primary monitor's scale factor.
#[cfg(not(target_os = "macos"))]
fn tray_px(app: &AppHandle) -> u32 {
    let scale = app
        .primary_monitor()
        .ok()
        .flatten()
        .map(|monitor| monitor.scale_factor())
        .unwrap_or(1.0);
    if scale < 1.25 {
        16
    } else if scale < 1.75 {
        20
    } else {
        32
    }
}

#[cfg(target_os = "macos")]
fn icon_for(_app: &AppHandle, status: &StatusView) -> tauri::Result<tauri::image::Image<'static>> {
    let bytes = if status.enabled { MAC_ON } else { MAC_OFF };
    if update::available().is_some() {
        return badged_template(bytes);
    }
    tauri::image::Image::from_bytes(bytes)
}

#[cfg(not(target_os = "macos"))]
fn icon_for(app: &AppHandle, status: &StatusView) -> tauri::Result<tauri::image::Image<'static>> {
    let bytes: &'static [u8] = match (status.enabled, tray_px(app)) {
        (true, 16) => ON_16,
        (true, 20) => ON_20,
        (false, 16) => OFF_16,
        (false, 20) => OFF_20,
        (true, _) => ON_32,
        (false, _) => OFF_32,
    };
    if update::available().is_some() {
        // Composed at runtime so the shipped PNGs stay untouched and the badge
        // always matches the size Windows asked for.
        return badged(bytes, tray_px(app));
    }
    tauri::image::Image::from_bytes(bytes)
}

// Update badge: an accent disc with a white download arrow in the bottom-right
// corner, plus a light halo so it reads on a dark taskbar too. Drawn from the
// pixels of the existing icon, not from an extra asset.
#[cfg(not(target_os = "macos"))]
const ACCENT: [u8; 3] = [0x58, 0x44, 0xC8];
#[cfg(not(target_os = "macos"))]
const HALO: [u8; 3] = [0xFF, 0xFF, 0xFF];

fn coverage(distance: f32, radius: f32) -> f32 {
    (radius - distance + 0.5).clamp(0.0, 1.0)
}

/// Source-over one pixel, straight alpha.
#[cfg(not(target_os = "macos"))]
fn blend(pixels: &mut [u8], index: usize, color: [u8; 3], alpha: f32) {
    let alpha = alpha.clamp(0.0, 1.0);
    if alpha <= 0.0 {
        return;
    }
    let dest = pixels[index + 3] as f32 / 255.0;
    let out = alpha + dest * (1.0 - alpha);
    if out <= 0.0 {
        return;
    }
    for channel in 0..3 {
        let dst = pixels[index + channel] as f32;
        let src = color[channel] as f32;
        pixels[index + channel] = ((src * alpha + dst * dest * (1.0 - alpha)) / out).round() as u8;
    }
    pixels[index + 3] = (out * 255.0).round() as u8;
}

#[cfg(not(target_os = "macos"))]
fn badged(base: &'static [u8], px: u32) -> tauri::Result<tauri::image::Image<'static>> {
    let image = tauri::image::Image::from_bytes(base)?;
    let (width, height) = (image.width(), image.height());
    let mut pixels = image.rgba().to_vec();

    // 8.6 px across at 16 px: visible in the notification area without hiding
    // the keycap.
    let radius = (px as f32 * 0.27).max(3.5);
    let cx = width as f32 - radius - 0.4;
    let cy = height as f32 - radius - 0.4;

    for y in 0..height {
        for x in 0..width {
            let dx = x as f32 + 0.5 - cx;
            let dy = y as f32 + 0.5 - cy;
            let distance = (dx * dx + dy * dy).sqrt();
            let index = ((y * width + x) * 4) as usize;

            let halo = coverage(distance, radius + 1.0);
            if halo > 0.0 {
                blend(&mut pixels, index, HALO, halo * 0.9);
            }
            let disc = coverage(distance, radius);
            if disc <= 0.0 {
                continue;
            }
            blend(&mut pixels, index, ACCENT, disc);

            let ax = dx.abs();
            let stem = ax <= 0.7 && dy >= -radius * 0.45 && dy <= radius * 0.15;
            let head =
                dy > radius * 0.15 && dy <= radius * 0.52 && ax <= (radius * 0.52 - dy) * 1.1 + 0.5;
            if stem || head {
                blend(&mut pixels, index, HALO, disc);
            }
        }
    }

    Ok(tauri::image::Image::new_owned(pixels, width, height))
}

// macOS update badge. The menu bar tints a template image itself, so the badge
// has to live in the alpha channel: a small solid dot in the bottom-right corner
// with a thin clear ring around it, so it stays apart from the keycap (filled
// `V` or outlined `E`) in both menu-bar appearances. The Windows badge is an
// accent-coloured disc with an arrow; a coloured menu-bar icon would have to be
// a non-template image, and then VietKB would have to pick white or black glyph
// pixels itself. The menu bar's tint follows the wallpaper under it as well as
// the light/dark setting (Sonoma and later), which no app can read reliably, so
// a wrong guess would leave a black glyph on a dark bar. The dot is kept small
// (an arrow does not survive 5 px) so the letter stays recognisable.
/// Badge dot radius in pixels of the 32 px template (18 pt @2x menu bar).
#[cfg(any(test, target_os = "macos"))]
const MAC_BADGE_RADIUS: f32 = 5.5;
/// Width of the clear ring around the dot.
#[cfg(any(test, target_os = "macos"))]
const MAC_BADGE_RING: f32 = 1.1;

/// Centre x, centre y, dot radius and ring width for a bitmap of this size.
#[cfg(any(test, target_os = "macos"))]
fn mac_badge_geometry(width: u32, height: u32) -> (f32, f32, f32, f32) {
    let scale = width as f32 / 32.0;
    let radius = MAC_BADGE_RADIUS * scale;
    let ring = MAC_BADGE_RING * scale;
    (
        width as f32 - radius - 0.5 * scale,
        height as f32 - radius - 0.5 * scale,
        radius,
        ring,
    )
}

/// Draw the badge into straight-alpha RGBA pixels of a black-on-transparent
/// template (RGB is left alone: only alpha carries the shape).
#[cfg(any(test, target_os = "macos"))]
fn badge_template_pixels(pixels: &mut [u8], width: u32, height: u32) {
    let (cx, cy, radius, ring) = mac_badge_geometry(width, height);

    for y in 0..height {
        for x in 0..width {
            let dx = x as f32 + 0.5 - cx;
            let dy = y as f32 + 0.5 - cy;
            let distance = (dx * dx + dy * dy).sqrt();
            let index = ((y * width + x) * 4) as usize;
            let alpha = pixels[index + 3] as f32 / 255.0;

            // Clear ring (and the dot area), then lay the dot on top.
            let cleared = alpha * (1.0 - coverage(distance, radius + ring));
            let out = cleared + coverage(distance, radius) * (1.0 - cleared);
            pixels[index + 3] = (out.clamp(0.0, 1.0) * 255.0).round() as u8;
        }
    }
}

#[cfg(target_os = "macos")]
fn badged_template(base: &'static [u8]) -> tauri::Result<tauri::image::Image<'static>> {
    let image = tauri::image::Image::from_bytes(base)?;
    let (width, height) = (image.width(), image.height());
    let mut pixels = image.rgba().to_vec();
    badge_template_pixels(&mut pixels, width, height);
    Ok(tauri::image::Image::new_owned(pixels, width, height))
}

fn tooltip(lang: Lang, status: &StatusView) -> String {
    let base = base_tooltip(lang, status.enabled);
    match update::available_version() {
        Some(version) => i18n::tf_in(
            lang,
            "tray.tip.update",
            &[("base", &base), ("version", &version)],
        ),
        None => base,
    }
}

/// The approved tooltip text (27-copy-decisions D), without the update note.
fn base_tooltip(lang: Lang, enabled: bool) -> String {
    i18n::tr(lang, if enabled { "tray.tip.on" } else { "tray.tip.off" }).to_string()
}

/// Exact label of the tray's update item, so the string is testable.
fn update_menu_label(lang: Lang, version: &str) -> String {
    i18n::tf_in(lang, "tray.update", &[("version", version)])
}

fn build_menu(app: &AppHandle, status: &StatusView) -> tauri::Result<Menu<Wry>> {
    let lang = i18n::current();
    let toggle = CheckMenuItem::with_id(
        app,
        "toggle",
        i18n::tr(lang, "tray.toggle"),
        true,
        status.enabled,
        None::<&str>,
    )?;

    let mut method_items = Vec::with_capacity(METHODS.len());
    for (slug, label) in METHODS {
        method_items.push(CheckMenuItem::with_id(
            app,
            format!("method:{slug}"),
            label,
            true,
            status.method == slug,
            None::<&str>,
        )?);
    }
    let method_refs: Vec<&dyn IsMenuItem<Wry>> = method_items
        .iter()
        .map(|item| item as &dyn IsMenuItem<Wry>)
        .collect();
    let method_menu = Submenu::with_items(app, i18n::tr(lang, "tray.method"), true, &method_refs)?;

    let settings = MenuItem::with_id(app, "settings", i18n::tr(lang, "tray.settings"), true, None::<&str>)?;
    let hotkeys = MenuItem::with_id(app, "hotkeys", i18n::tr(lang, "tray.hotkeys"), true, None::<&str>)?;
    let about = MenuItem::with_id(app, "about", i18n::tr(lang, "tray.about"), true, None::<&str>)?;
    // Only while a newer release is known: the item is the tray's third
    // affordance, and it must appear without a restart when the 5 s check finds
    // one (`refresh` rebuilds this menu).
    let update_item = match update::available_version() {
        Some(version) => {
            tracing::debug!(%version, "tray: update item added");
            Some(MenuItem::with_id(
                app,
                "update",
                update_menu_label(lang, &version),
                true,
                None::<&str>,
            )?)
        }
        None => None,
    };
    let quit = MenuItem::with_id(app, "quit", i18n::tr(lang, "tray.quit"), true, None::<&str>)?;
    let sep_top = PredefinedMenuItem::separator(app)?;
    let sep_open = PredefinedMenuItem::separator(app)?;
    let sep_about = PredefinedMenuItem::separator(app)?;
    let sep_bottom = PredefinedMenuItem::separator(app)?;

    let mut items: Vec<&dyn IsMenuItem<Wry>> = vec![
        &toggle,
        &sep_top,
        &method_menu,
        &sep_open,
        &settings,
        &hotkeys,
        &sep_about,
    ];
    if let Some(item) = &update_item {
        items.push(item);
    }
    items.push(&about);
    items.push(&sep_bottom);
    items.push(&quit);
    Menu::with_items(app, &items)
}

/// Create the tray icon with the current state. Called once during setup.
pub fn install(app: &AppHandle) -> tauri::Result<()> {
    let status = commands::status_now();
    let menu = build_menu(app, &status)?;

    let builder = TrayIconBuilder::with_id(TRAY_ID)
        .icon(icon_for(app, &status)?)
        .tooltip(tooltip(i18n::current(), &status))
        .menu(&menu)
        .on_menu_event(|app, event| handle_event(app, event.id.as_ref()));

    // Left click toggles Vietnamese on/off, the menu is right-click only. Same
    // on both platforms (M10). On macOS ctrl-click also opens the menu:
    // tray-icon 0.25.1 reports it as a plain Left click with no modifier info,
    // so the handler reads the live modifier flags itself.
    let builder = builder
        .show_menu_on_left_click(false)
        .on_tray_icon_event(|tray, event| {
            // `Up`, not `Down`: one toggle per physical click.
            if let TrayIconEvent::Click {
                button: MouseButton::Left,
                button_state: MouseButtonState::Up,
                ..
            } = event
            {
                #[cfg(target_os = "macos")]
                if control_held() {
                    show_menu_async(tray);
                    return;
                }
                #[cfg(not(target_os = "macos"))]
                let _ = tray;
                toggle_from_left_click();
            }
        });

    // macOS: the icon is a template image the system tints.
    #[cfg(target_os = "macos")]
    let builder = builder.icon_as_template(true);

    builder.build(app)?;

    Ok(())
}

/// True while the Control key is down (`+[NSEvent modifierFlags]`, the state
/// at the time of the call, which is the click we are handling).
#[cfg(target_os = "macos")]
fn control_held() -> bool {
    use objc2_app_kit::{NSEvent, NSEventModifierFlags};
    NSEvent::modifierFlags_class().contains(NSEventModifierFlags::Control)
}

/// Pop the tray menu programmatically. Tauri has no public call for it, so go
/// through `with_inner_tray_icon` to tray-icon's `show_menu`, which attaches the
/// menu to the NSStatusItem and `performClick`s its button. Done from a helper
/// thread because `with_inner_tray_icon` blocks until the main thread has run
/// the closure, and we are already inside a main-thread event callback.
#[cfg(target_os = "macos")]
fn show_menu_async(tray: &tauri::tray::TrayIcon) {
    let tray = tray.clone();
    std::thread::spawn(move || {
        let _ = tray.with_inner_tray_icon(|inner| inner.show_menu());
    });
}

/// Swallow the second half of a double-click. Windows reports a double-click on
/// the tray as extra click events; without this guard one double-click would
/// flip the state twice and land back where it started.
const CLICK_GUARD: Duration = Duration::from_millis(350);

fn toggle_from_left_click() {
    static LAST_CLICK: Mutex<Option<Instant>> = Mutex::new(None);

    let now = Instant::now();
    let Ok(mut last) = LAST_CLICK.lock() else {
        return;
    };
    if last.is_some_and(|previous| now.duration_since(previous) < CLICK_GUARD) {
        return;
    }
    *last = Some(now);
    drop(last);

    // Same path as the menu item: persist, set `enabled` on the hook, patch the
    // tray icon and tooltip, broadcast to the open windows.
    let _ = commands::toggle_enabled();
}

/// Rebuild the menu and icon after any state change. Never panics: a tray that
/// fails to refresh must not take the app down.
pub fn refresh(app: &AppHandle, status: &StatusView) {
    if let Err(error) = try_refresh(app, status) {
        tracing::warn!(%error, "could not refresh tray menu");
    }
}

fn try_refresh(app: &AppHandle, status: &StatusView) -> tauri::Result<()> {
    let Some(tray) = app.tray_by_id(TRAY_ID) else {
        return Ok(());
    };
    let menu = build_menu(app, status)?;
    tray.set_menu(Some(menu))?;
    tray.set_icon(Some(icon_for(app, status)?))?;
    // `set_icon` may reset the template flag; set it again.
    #[cfg(target_os = "macos")]
    tray.set_icon_as_template(true)?;
    tray.set_tooltip(Some(tooltip(i18n::current(), status)))?;
    Ok(())
}

fn handle_event(app: &AppHandle, id: &str) {
    match id {
        "quit" => crate::quit(app),
        "settings" => crate::show_settings(app),
        "update" => crate::show_about(app),
        "about" => crate::show_about(app),
        "hotkeys" => {
            if let Err(error) = crate::show_aux(app, "hotkeys") {
                tracing::warn!(%error, "tray: could not open the hotkeys window");
            }
        }
        "toggle" => {
            let _ = commands::toggle_enabled();
        }
        _ => {
            if let Some(slug) = id.strip_prefix("method:") {
                if let Err(error) = commands::set_method(slug.to_string()) {
                    tracing::warn!(%error, "tray: set method failed");
                }
            }
        }
    }
}
#[cfg(test)]
mod tests {
    use super::*;

    /// The macOS badge stays a template (RGB untouched, shape in alpha), adds a
    /// solid dot in the bottom-right corner with a clear ring, and leaves the
    /// keycap alone everywhere outside the dot and ring.
    #[test]
    fn mac_badge_is_alpha_only_and_keeps_the_keycap() {
        let size = 32u32;
        let mut pixels = vec![0u8; (size * size * 4) as usize];
        for px in pixels.chunks_exact_mut(4) {
            px[3] = 255;
        }
        let original = pixels.clone();
        badge_template_pixels(&mut pixels, size, size);

        let alpha = |p: &[u8], x: u32, y: u32| p[((y * size + x) * 4 + 3) as usize];
        assert!(pixels.chunks_exact(4).all(|px| px[..3] == [0, 0, 0]));
        assert_eq!(alpha(&pixels, 2, 2), alpha(&original, 2, 2));
        let (cx, cy, radius, _) = mac_badge_geometry(size, size);
        // Dot centre solid; a pixel in the ring is mostly clear.
        assert_eq!(alpha(&pixels, cx as u32, cy as u32), 255);
        assert!(alpha(&pixels, (cx - radius - 0.6) as u32, cy as u32) < 128);
    }

    /// The badge must not eat the letter: on the real V and E images at both
    /// sizes, every pixel farther than dot + ring + 1 px from the badge centre
    /// is unchanged and most of the glyph's opaque pixels survive.
    /// `VKB_DUMP_BADGE=1 cargo test -p vkb-app mac_badge -- --nocapture` prints
    /// the four badged images as text.
    #[cfg(target_os = "macos")]
    #[test]
    fn mac_badge_leaves_the_glyph_recognisable() {
        for (name, bytes) in [
            ("on-32", MAC_ON),
            ("off-32", MAC_OFF),
            ("on-16", include_bytes!("../icons/tray-mac-on-16.png").as_slice()),
            ("off-16", include_bytes!("../icons/tray-mac-off-16.png").as_slice()),
        ] {
            let image = tauri::image::Image::from_bytes(bytes).unwrap();
            let (w, h) = (image.width(), image.height());
            let before = image.rgba().to_vec();
            let mut after = before.clone();
            badge_template_pixels(&mut after, w, h);
            let (cx, cy, radius, ring) = mac_badge_geometry(w, h);
            let mut opaque_before = 0u32;
            let mut opaque_after = 0u32;
            for y in 0..h {
                for x in 0..w {
                    let i = ((y * w + x) * 4 + 3) as usize;
                    let d = ((x as f32 + 0.5 - cx).powi(2) + (y as f32 + 0.5 - cy).powi(2)).sqrt();
                    if d > radius + ring + 1.0 {
                        assert_eq!(before[i], after[i], "{name}: pixel {x},{y} changed");
                    }
                    opaque_before += u32::from(before[i] > 128);
                    opaque_after += u32::from(after[i] > 128);
                }
            }
            assert!(
                opaque_after * 10 >= opaque_before * 8,
                "{name}: badge removed too much of the glyph ({opaque_before} -> {opaque_after})"
            );
            if std::env::var_os("VKB_DUMP_BADGE").is_some() {
                eprintln!("--- {name} ---");
                for y in 0..h {
                    let row: String = (0..w)
                        .map(|x| match after[((y * w + x) * 4 + 3) as usize] {
                            0..=40 => '.',
                            41..=170 => '+',
                            _ => '#',
                        })
                        .collect();
                    eprintln!("{row}");
                }
            }
        }
    }

    /// The tray's third affordance names the exact version, so the string is
    /// asserted here rather than discovered by reading the menu.
    #[test]
    fn update_item_label_names_the_version() {
        assert_eq!(update_menu_label(Lang::Vi, "0.9.9"), "Có bản cập nhật v0.9.9");
        assert_eq!(update_menu_label(Lang::En, "0.9.9"), "Update v0.9.9 available");
    }

    /// S-19: the tooltip is the approved copy in both languages.
    #[test]
    fn tooltip_is_the_approved_copy() {
        assert_eq!(base_tooltip(Lang::Vi, true), "VietKB — đang gõ tiếng Việt");
        assert_eq!(base_tooltip(Lang::Vi, false), "VietKB — đã tắt tiếng Việt");
        assert_eq!(base_tooltip(Lang::En, true), "VietKB — Vietnamese on");
        assert_eq!(base_tooltip(Lang::En, false), "VietKB — Vietnamese off");
    }

    /// Every window the app opens must be in the capability file, or its close
    /// button and IPC are refused at runtime.
    #[test]
    fn every_window_has_a_capability() {
        let capability = include_str!("../capabilities/default.json");
        let line = capability
            .lines()
            .find(|line| line.trim_start().starts_with("\"windows\""))
            .expect("capabilities/default.json has no \"windows\" array");
        let start = line.find('[').expect("no [ in the windows line");
        let end = line.find(']').expect("no ] in the windows line");
        let mut labels: Vec<&str> = line[start + 1..end]
            .split(',')
            .map(|label| label.trim().trim_matches('"'))
            .filter(|label| !label.is_empty())
            .collect();
        labels.sort_unstable();
        assert_eq!(labels, ["about", "advanced", "hotkeys", "macros", "main"]);
    }
}
