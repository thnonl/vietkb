const MIN_PREFIX_LEN: usize = 4;

/// Returns `true` when the raw typed word looks like an English word (exact
/// match) or is a long-enough prefix of one, and therefore should not be
/// transformed to Vietnamese.
pub fn is_english_word(raw: &str) -> bool {
    if raw.len() < MIN_PREFIX_LEN {
        return false;
    }

    let lower = raw.to_ascii_lowercase();
    ENGLISH_WORDS
        .iter()
        .any(|word| *word == lower || (word.len() > lower.len() && word.starts_with(&lower)))
}

#[cfg(test)]
mod tests {
    use super::is_english_word;

    #[test]
    fn detects_common_words() {
        assert!(is_english_word("window"));
        assert!(is_english_word("windows"));
        assert!(is_english_word("google"));
        assert!(is_english_word("install"));
        assert!(is_english_word("setting"));
    }

    #[test]
    fn ignores_vietnamese_syllables() {
        assert!(!is_english_word("tie"));
        assert!(!is_english_word("duo"));
        assert!(!is_english_word("hoa"));
        assert!(!is_english_word("ng"));
    }
}
