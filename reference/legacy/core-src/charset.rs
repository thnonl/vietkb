use crate::engine::Charset;

pub fn convert_output(text: &str, charset: Charset) -> String {
    match charset {
        Charset::Unicode => text.to_owned(),
        Charset::VniWindows => text.chars().map(vni_windows_char).collect(),
        Charset::Tcvn3 => text.chars().map(tcvn3_char).collect(),
    }
}

